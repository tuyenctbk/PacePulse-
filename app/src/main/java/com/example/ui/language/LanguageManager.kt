    private val _currentLanguage = MutableStateFlow(supportedLanguages[0])
    val currentLanguage: StateFlow<AppLanguage> = _currentLanguage.asStateFlow()

    private val _strings = MutableStateFlow(translations["en"]!!)
    val strings: StateFlow<AppStrings> = _strings.asStateFlow()

    private var prefs: SharedPreferences? = null

    fun init(context: Context) {
        prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val savedCode = prefs?.getString(KEY_LANG, "en") ?: "en"
        setLanguage(savedCode)
    }

    fun setLanguage(code: String) {
        val lang = supportedLanguages.find { it.code == code } ?: supportedLanguages[0]
        _currentLanguage.value = lang
        _strings.value = translations[lang.code] ?: translations["en"]!!
        prefs?.edit()?.putString(KEY_LANG, lang.code)?.apply()
    }
